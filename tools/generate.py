def camel(name):
    parts = re.split(r"[^A-Za-z0-9]+", name)
    head = parts[0][0].lower() + parts[0][1:] if parts[0] else ""
    result = head + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return result + "_" if result in JAVA_KEYWORDS else result


def pascal(name):
    value = camel(name.rstrip("_"))
    return value[:1].upper() + value[1:]


def constant(value):
    name = re.sub(r"[^A-Za-z0-9]+", "_", value).strip("_").upper()
    return "_" + name if name[:1].isdigit() else name


def escape_doc(text):
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("@", "{@literal @}").replace("\\", "&#92;").replace("*/", "*&#47;")
    text = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", text)
    return re.sub(r"`([^`]+)`", lambda m: "<code>" + m.group(1).replace("{", "&#123;").replace("}", "&#125;")
                  + "</code>", text)


def doc(text, indent, extra=()):
    """A Javadoc block. `extra` lines are block tags, already written."""
    pad = " " * indent
    paragraphs = [p for p in re.split(r"\n\s*\n", (text or "").strip()) if p.strip()]
    lines = []
    for index, paragraph in enumerate(paragraphs):
        flat = " ".join(line.strip() for line in paragraph.splitlines())
        escaped = escape_doc(flat)
        if index:
            lines.append("")
            escaped = "<p>" + escaped
        lines.extend(textwrap.wrap(escaped, 112 - indent, break_long_words=False, break_on_hyphens=False))
    if extra:
        if lines:
            lines.append("")
        lines.extend(extra)
    if not lines:
        lines = ["See the Rask API reference."]
    if len(lines) == 1:
        return f"{pad}/** {lines[0]} */\n"
    body = "".join(f"{pad} * {line}".rstrip() + "\n" for line in lines)
    return f"{pad}/**\n{body}{pad} */\n"


class Spec:
    def __init__(self, data):
        self.data = data
        self.schemas = data["components"]["schemas"]
        self.parameters = data["components"]["parameters"]
        self.request_reachable = set()
        self.variant_of = {}
        for name, schema in self.schemas.items():
            if "oneOf" in schema:
                prop = schema["discriminator"]["propertyName"]
                mapping = schema["discriminator"]["mapping"]
                for branch in schema["oneOf"]:
                    variant = ref_name(branch)
                    if variant in self.variant_of:
                        sys.exit(f"{variant} is in two unions; interfaces would clash")
                    values = sorted(v for v, target in mapping.items() if target.endswith("/" + variant))
                    self.variant_of[variant] = (name, prop, values)
        self.operations = []
        for path, item in data["paths"].items():
            for method in METHODS:
                if method in item:
                    self.operations.append(self.operation(path, method, item))
        for operation in self.operations:
            if operation["body"]:
                self.reach(operation["body"]["schema"])

    def reach(self, node):
        if isinstance(node, dict):
            if "$ref" in node:
                name = ref_name(node)
                if name in self.schemas and name not in self.request_reachable:
                    self.request_reachable.add(name)
                    self.reach(self.schemas[name])
            for value in node.values():
                self.reach(value)
        elif isinstance(node, list):
            for value in node:
                self.reach(value)

    def operation(self, path, method, item):
        raw = item[method]
        params = [self.parameter(p) for p in item.get("parameters", []) + raw.get("parameters", [])]
        body = None
        if "requestBody" in raw:
            content = raw["requestBody"]["content"]["application/json"]
            body = {"schema": content["schema"], "required": raw["requestBody"].get("required", False)}
        response = None
        status = None
        for code in sorted(raw["responses"]):
            if code.startswith("2"):
                status = code
                answer = raw["responses"][code]
                if "$ref" in answer:
                    answer = self.data["components"]["responses"][ref_name(answer)]
                content = answer.get("content", {}).get("application/json")
                response = content["schema"] if content else None
                break
        tag = raw["tags"][0]
        if path.startswith("/folders"):
            tag = "Folders"
        return {
            "id": raw["operationId"],
            "method": method.upper(),
            "path": path,
            "tag": tag,
            "summary": raw.get("summary", ""),
            "description": raw.get("description", ""),
            "deprecated": raw.get("deprecated", False),
            "path_params": sorted((p for p in params if p["in"] == "path"), key=lambda p: path.index("{" + p["name"] + "}")),
            "query_params": [p for p in params if p["in"] == "query"],
            "headers": {p["name"]: p for p in params if p["in"] == "header"},
            "body": body,
            "response": response,
            "status": status,
            "paged": raw.get("x-rask-operation", {}).get("pagination") == "cursor",
        }

    def parameter(self, node):
        return self.parameters[ref_name(node)] if "$ref" in node else node

    def kind(self, name):
        schema = self.schemas[name]
        if "enum" in schema:
            return "enum"
        if "oneOf" in schema:
            return "union"
        return "object"


def ref_name(node):
    return node["$ref"].rsplit("/", 1)[-1]


class Field:
    """How one JSON value appears in Java."""

    def __init__(self, java, read, setter=None, imports=()):
        self.java = java
        self.read = read
        self.setter = setter or java
        self.imports = set(imports)


def field_of(spec, schema, name):
    """`name` is the JSON member name for the getter expression."""
    if "anyOf" in schema:
        branches = [b for b in schema["anyOf"] if b.get("type") != "null"]
        if len(branches) != 1:
            sys.exit(f"unsupported anyOf at {name}: {schema}")
        return field_of(spec, branches[0], name)
    if "$ref" in schema:
        target = ref_name(schema)
        if spec.kind(target) == "enum":
            return Field(target, f'enm("{name}", {target}::of)')
        return Field(target, f'obj("{name}", {target}::of)')
    kind = schema.get("type")
    if isinstance(kind, list):
        kind = next(k for k in kind if k != "null")
    fmt = schema.get("format")
    if kind == "string":
        if fmt == "date-time":
            return Field("OffsetDateTime", f'time("{name}")', imports=["java.time.OffsetDateTime"])
        if fmt == "date":
            return Field("LocalDate", f'day("{name}")', imports=["java.time.LocalDate"])
        return Field("String", f'str("{name}")')
    if kind == "integer":
        if fmt == "int64":
            return Field("Long", f'i64("{name}")', setter="long")
        return Field("Integer", f'i32("{name}")', setter="int")
    if kind == "number":
        return Field("Double", f'num("{name}")', setter="double")
    if kind == "boolean":
        return Field("Boolean", f'bool("{name}")', setter="boolean")
    if kind == "array":
        items = schema["items"]
        item = field_of(spec, items, name)
        imports = {"java.util.List"} | item.imports
        if "$ref" in items and spec.kind(ref_name(items)) == "enum":
            return Field(f"List<{item.java}>", f'enms("{name}", {item.java}::of)', imports=imports)
        if "$ref" in items:
            return Field(f"List<{item.java}>", f'objs("{name}", {item.java}::of)', imports=imports)
        if item.java == "String":
            return Field("List<String>", f'strs("{name}")', imports=imports)
        sys.exit(f"unsupported array items at {name}: {items}")
    if kind == "object" and isinstance(schema.get("additionalProperties"), dict):
        return Field("Map<String, String>", f'strMap("{name}")', imports=["java.util.Map"])
    sys.exit(f"unsupported schema at {name}: {schema}")


def imports_block(imports):
    lines = "".join(f"import {name};\n" for name in sorted(imports))
    return lines + "\n" if lines else ""


def write(out, relative, content):
    path = os.path.join(out, PACKAGE.replace(".", "/"), relative)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(content)


def generate_enum(spec, name, schema, out):
    values = schema["enum"]
    known = {}
    for value in values:
        known[constant(value)] = value
    constants = "".join(f'    /** {escape_doc(value)} */\n    public static final {name} {const} = new {name}("{value}", true);\n'
                        for const, value in known.items())
    cases = "".join(f'            case "{value}":\n                return {const};\n' for const, value in known.items())
    open_note = "" if schema.get("x-rask-open-enum") else "\n\nThe server only accepts the listed values today."
    content = f"""{HEADER}package {PACKAGE}.model;

{doc(schema.get('description', '') + open_note, 0).rstrip()}
public final class {name} extends OpenEnum {{
{constants}
    private {name}(String value, boolean known) {{
        super(value, known);
    }}

    /**
     * Returns the value for a wire string, keeping strings this SDK version does not list.
     *
     * @param value the wire string
     * @return the value; null for a null string
     */
    public static {name} of(String value) {{
        if (value == null) {{
            return null;
        }}
        switch (value) {{
{cases}            default:
                return new {name}(value, false);
        }}
    }}
}}
"""
    write(out, f"model/{name}.java", content)


def generate_union(spec, name, schema, out):
    prop = schema["discriminator"]["propertyName"]
    mapping = schema["discriminator"]["mapping"]
    cases = "".join(f'                case "{value}":\n                    return {target.rsplit("/", 1)[-1]}.of(raw);\n'
                    for value, target in mapping.items())
    note = (f"A value of `{prop}` this SDK version does not know decodes to `Unknown`, which keeps every member; "
            "see `RaskValue#raw()`.")
    content = f"""{HEADER}package {PACKAGE}.model;

import java.util.Map;

{doc((schema.get('description', '') + chr(10) + chr(10) + note).strip(), 0).rstrip()}
public interface {name} extends RaskValue {{
    /**
     * Picks the variant by <code>{prop}</code>. Never fails: an unknown value gives {{@link Unknown}}.
     *
     * @param raw the decoded JSON object
     * @return the variant
     */
    static {name} of(Map<String, Object> raw) {{
        Object tag = raw.get("{prop}");
        if (tag instanceof String) {{
            switch ((String) tag) {{
{cases}                default:
                    break;
            }}
        }}
        return new Unknown(raw);
    }}

    /**
     * Returns the value of <code>{prop}</code>, known to this SDK version or not.
     *
     * @return the wire string
     */
    String discriminator();

    /**
     * Tells whether this SDK version does not know this variant.
     *
     * @return true for {{@link Unknown}}
     */
    default boolean isUnknown() {{
        return false;
    }}

    /** A variant added to the API after this SDK version was built. */
    final class Unknown extends RaskModel implements {name} {{
        Unknown(Map<String, Object> raw) {{
            super(raw);
        }}

        @Override
        public String discriminator() {{
            return str("{prop}");
        }}

        @Override
        public boolean isUnknown() {{
            return true;
        }}
    }}
}}
"""
    write(out, f"model/{name}.java", content)


def generate_object(spec, name, schema, out):
    properties = schema.get("properties", {})
    imports = {"java.util.Map"}
    getters = []
    variant = spec.variant_of.get(name)
    implements = ""
    if variant:
        implements = f" implements {variant[0]}"
        getters.append(f"""    @Override
    public String discriminator() {{
        return str("{variant[1]}");
    }}
""")
    fields = {}
    for prop, prop_schema in properties.items():
        method = camel(prop)
        if method in RESERVED_MEMBERS:
            method += "_"
        field = field_of(spec, prop_schema, prop)
        fields[prop] = (method, field, prop_schema)
        imports |= field.imports
        deprecated = prop_schema.get("deprecated", False)
        extra = ["@deprecated see the Rask API changelog"] if deprecated else []
        getters.append(doc(prop_schema.get("description") or spec.schemas.get(
            ref_name(prop_schema) if "$ref" in prop_schema else "", {}).get("description", ""), 4, extra)
            + ("    @Deprecated\n" if deprecated else "")
            + f"""    public {field.java} {method}() {{
        return {field.read};
    }}
""")
    if not properties and isinstance(schema.get("additionalProperties"), dict):
        getters.append("""    /**
     * Returns the entries.
     *
     * @return an unmodifiable map
     */
    public Map<String, String> asMap() {
        return stringsOf(raw());
    }
""")
    builder = ""
    if name in spec.request_reachable:
        preset = ""
        required = list(schema.get("required", []))
        setters = []
        for prop, (method, field, prop_schema) in fields.items():
            if variant and prop == variant[1] and len(variant[2]) == 1:
                preset = f'''            set("{prop}", "{variant[2][0]}");\n'''
                required = [r for r in required if r != prop]
                continue
            setters.append(doc(prop_schema.get("description") or spec.schemas.get(
                ref_name(prop_schema) if "$ref" in prop_schema else "", {}).get("description", ""), 8)
                + f"""        public Builder {method}({field.setter} value) {{
            return set("{prop}", value);
        }}
""")
        checks = ""
        if required:
            quoted = ", ".join(f'"{r}"' for r in required)
            checks += f'            require("{name}", {quoted});\n'
        if schema.get("minProperties"):
            checks += f'            requireAtLeast("{name}", {schema["minProperties"]});\n'
        builder = f"""
    /**
     * Starts this request.
     *
     * @return a new builder
     */
    public static Builder builder() {{
        return new Builder();
    }}

    /** Builds {{@link {name}}}. A field left unset is omitted from the JSON. */
    public static final class Builder extends ModelBuilder<Builder> {{
        private Builder() {{
{preset}        }}

{chr(10).join(setters)}{chr(10) if setters else ''}        /**
         * Finishes the request.
         *
         * @return the request
         * @throws IllegalArgumentException when a field the contract requires is missing
         */
        public {name} build() {{
{checks}            return new {name}(values());
        }}
    }}
"""
    body = "\n".join(getters)
    content = f"""{HEADER}package {PACKAGE}.model;

{imports_block(imports)}{doc(schema.get('description', ''), 0).rstrip()}
public final class {name} extends RaskModel{implements} {{
    private {name}(Map<String, Object> raw) {{
        super(raw);
    }}

    /**
     * Wraps a decoded JSON object. Never fails: members this SDK version does not expect stay in {{@link #raw()}}.
     *
     * @param raw the decoded JSON object
     * @return the view
     */
    public static {name} of(Map<String, Object> raw) {{
        return new {name}(raw);
    }}
{chr(10) + body if body else ''}{builder}}}
"""
    write(out, f"model/{name}.java", content)


def params_class_name(operation):
    return pascal(operation["id"]) + "Params"


def generate_params(spec, operation, out):
    name = params_class_name(operation)
    imports = set()
    setters = []
    required = []
    for param in operation["query_params"]:
        method = camel(param["name"])
        field = field_of(spec, param["schema"], param["name"])
        imports |= field.imports
        setter = field.setter
        if "$ref" in param["schema"] or field.java.startswith("List<"):
            imports |= {f"{PACKAGE}.model.{t}" for t in re.findall(r"\b([A-Z]\w+)\b", field.java)
                        if t in spec.schemas}
        if param.get("required"):
            required.append(param["name"])
        setters.append(doc(param.get("description", ""), 8)
                       + f"""        public Builder {method}({setter} value) {{
            return set("{param['name']}", value);
        }}
""")
    checks = ""
    if required:
        quoted = ", ".join(f'"{r}"' for r in required)
        checks = f'            require("{operation["id"]}", {quoted});\n'
    content = f"""{HEADER}package {PACKAGE}.params;

{imports_block(imports)}/** Query parameters of <code>{operation['id']}</code>. */
public final class {name} extends QueryParams {{
    private {name}(Builder builder) {{
        super(builder);
    }}

    /**
     * Starts the parameters.
     *
     * @return a new builder
     */
    public static Builder builder() {{
        return new Builder();
    }}

    /** Builds {{@link {name}}}. */
    public static final class Builder extends QueryParams.Builder<Builder> {{
        private Builder() {{
        }}

{chr(10).join(setters)}
        /**
         * Finishes the parameters.
         *
         * @return the parameters
         */
        public {name} build() {{
{checks}            return new {name}(this);
        }}
    }}
}}
"""
    write(out, f"params/{name}.java", content)


