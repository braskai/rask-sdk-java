"""Generates the Java models, query parameter classes and resources from the Rask API v3 contract.

Standard library only. Usage: python3 tools/generate.py [--spec spec/openapi.json] [--out src/main/java]

Why not Kiota or OpenAPI Generator: DESIGN 11.1 measured Kiota Java 14/17 (unknown union variants lose every field and
fail to serialize) and OpenAPI Generator 7.27 6/17. Both also name methods by path, not by operationId, and bring
runtime dependencies. This generator writes views over the decoded JSON, so nothing the server adds can be fatal.
"""
