def generate_resource(spec, tag, operations, out):
    _, class_name = RESOURCES[tag]
    imports = {f"{PACKAGE}.RaskResponse", f"{PACKAGE}.RequestOptions", f"{PACKAGE}.internal.Operation",
               f"{PACKAGE}.internal.Transport"} | EXTRA_IMPORTS.get(tag, set())
    constants = []
    methods = []
    for operation in operations:
        constant_name = constant(re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", operation["id"]))
        headers = operation["headers"]
        key = "KEYED" if "Idempotency-Key" in headers else "NONE"
        if_match = "NONE"
        if "If-Match" in headers:
            if_match = "REQUIRED" if headers["If-Match"].get("required") else "OPTIONAL"
        if_none = "true" if "If-None-Match" in headers else "false"
        constants.append(f"""    private static final Operation {constant_name} = new Operation(
            "{operation['id']}", "{operation['method']}", "{operation['path']}",
            Operation.KeyPolicy.{key}, Operation.IfMatchPolicy.{if_match}, {if_none});
""")
        args = []  # (java type, name, doc)
        for param in operation["path_params"]:
            field = field_of(spec, param["schema"], param["name"])
            java = "int" if field.java == "Integer" else field.java
            args.append((java, camel(param["name"]), param.get("description", "") or param["name"]))
        path_args = ", ".join(a[1] for a in args)
        required_match = if_match == "REQUIRED"
        if required_match:
            args.append(("String", "ifMatch", "the ETag read from the resource, quotes included"))
        body = operation["body"]
        body_type = None
        if body:
            body_type = ref_name(body["schema"])
            imports.add(f"{PACKAGE}.model.{body_type}")
        has_query = bool(operation["query_params"])
        params_type = params_class_name(operation) if has_query else None
        query_required = any(p.get("required") for p in operation["query_params"])
        if has_query:
            imports.add(f"{PACKAGE}.params.{params_type}")
            generate_params(spec, operation, out)
        response = operation["response"]
        result = ref_name(response) if response else "Void"
        decode = f"{result}::of" if response else "null"
        if response:
            imports.add(f"{PACKAGE}.model.{result}")
        name = camel(operation["id"])
        summary = operation["summary"] or operation["id"]
        deprecated = operation["deprecated"]
        deprecation_tag = ["@deprecated see the Rask API changelog"] if deprecated else []
        annotation = "    @Deprecated\n" if deprecated else ""

        def signature(*parts):
            return ", ".join(f"{t} {n}" for t, n in parts)

        leading = [(a[0], a[1]) for a in args]
        names = [a[1] for a in args]
        tags = [f"@param {a[1]} {escape_doc(a[2])}" for a in args]
        last = []
        call_names = list(names)
        if body:
            last.append((body_type, "body"))
            tags.append("@param body the request" + (", or null to send none" if not body["required"] else ""))
        if has_query:
            last.append((params_type, "params"))
            tags.append("@param params the query parameters" + ("" if query_required else ", or null"))
        full_doc = doc(summary + "\n\n" + operation["description"] if operation["description"] else summary, 4,
                       tags + ["@param options per-call settings, or null",
                               "@return the result, with raw status and headers"] + deprecation_tag)
        if_match_arg = "ifMatch" if required_match else "null"
        body_arg = "body" if body else "null"
        params_arg = "params" if has_query else "null"
        checks = ""
        if body and body["required"]:
            checks = f'''        if (body == null) {{
            throw new IllegalArgumentException("{operation['id']} requires a body");
        }}
'''
        if has_query and query_required:
            checks += f'''        if (params == null) {{
            throw new IllegalArgumentException("{operation['id']} requires its query parameters");
        }}
'''
        methods.append(full_doc + annotation + f"""    public RaskResponse<{result}> {name}({signature(*leading, *last, ('RequestOptions', 'options'))}) {{
{checks}        return transport.execute({constant_name}, new Object[] {{{path_args}}}, {params_arg}, {body_arg},
                {if_match_arg}, options, {decode});
    }}
""")
        short_doc = doc(summary, 4, [f"@param {a[1]} {escape_doc(a[2])}" for a in args]
                        + [t for t in tags if t.startswith("@param body") or t.startswith("@param params")]
                        + ["@return the result, with raw status and headers"] + deprecation_tag)
        call = ", ".join(call_names + [n for _, n in last] + ["null"])
        methods.append(short_doc + annotation + f"""    public RaskResponse<{result}> {name}({signature(*leading, *last)}) {{
        return {name}({call});
    }}
""")
        optional_last = (body and not body["required"]) or (has_query and not query_required)
        if optional_last and len(last) == 1:
            nulls = ", ".join(call_names + ["null", "null"])
            methods.append(doc(summary, 4, [f"@param {a[1]} {escape_doc(a[2])}" for a in args]
                               + ["@return the result, with raw status and headers"] + deprecation_tag)
                           + annotation + f"""    public RaskResponse<{result}> {name}({signature(*leading)}) {{
        return {name}({nulls});
    }}
""")
        if operation["paged"]:
            imports.add(f"{PACKAGE}.PageIterable")
            item = field_of(spec, spec.schemas[result]["properties"]["data"]["items"], "data").java
            imports.add(f"{PACKAGE}.model.{item}")
            walk = name + "AutoPaging"
            walk_tags = [f"@param {a[1]} {escape_doc(a[2])}" for a in args]
            methods.append(doc(f"{summary} Walks every page, fetching each only when needed.", 4,
                               walk_tags + ["@param params the filters, kept on every page, or null",
                                            "@param options per-call settings, or null",
                                            "@return the items"] + deprecation_tag)
                           + annotation + f"""    public PageIterable<{item}> {walk}({signature(*leading, (params_type, 'params'), ('RequestOptions', 'options'))}) {{
        return PageIterable.of(cursor -> transport.page({constant_name}, new Object[] {{{path_args}}}, params, cursor,
                options, {result}::of), {result}::data, {result}::nextCursor);
    }}
""")
            methods.append(doc(f"{summary} Walks every page, fetching each only when needed.", 4,
                               walk_tags + ["@param params the filters, kept on every page, or null",
                                            "@return the items"] + deprecation_tag)
                           + annotation + f"""    public PageIterable<{item}> {walk}({signature(*leading, (params_type, 'params'))}) {{
        return {walk}({', '.join(names + ['params', 'null'])});
    }}
""")
            if not query_required:
                methods.append(doc(f"{summary} Walks every page, fetching each only when needed.", 4,
                                   walk_tags + ["@return the items"] + deprecation_tag)
                               + annotation + f"""    public PageIterable<{item}> {walk}({signature(*leading)}) {{
        return {walk}({', '.join(names + ['null', 'null'])});
    }}
""")
    description = spec_tag_description(spec, tag)
    content = f"""{HEADER}package {PACKAGE}.resources;

{imports_block(imports)}{doc(description, 0).rstrip()}
public final class {class_name} {{
{EXTRA_CONSTANTS.get(tag, '')}{''.join(constants)}
    private final Transport transport;

    /**
     * Creates the resource. Reach it through the client instead.
     *
     * @param transport the client's transport
     */
    public {class_name}(Transport transport) {{
        this.transport = transport;
    }}

{chr(10).join(methods)}{EXTRA_MEMBERS.get(tag, '')}}}
"""
    write(out, f"resources/{class_name}.java", content)


def spec_tag_description(spec, tag):
    if tag == "Folders":
        return "Folders that organize projects."
    for entry in spec.data.get("tags", []):
        if entry["name"] == tag:
            return entry.get("description", tag)
    return tag


def generate_resources_accessors(spec, tags, out):
    imports = {f"{PACKAGE}.internal.Transport"}
    fields = []
    assigns = []
    accessors = []
    for tag in tags:
        accessor, class_name = RESOURCES[tag]
        imports.add(f"{PACKAGE}.resources.{class_name}")
        fields.append(f"    private final {class_name} {accessor};\n")
        assigns.append(f"        this.{accessor} = new {class_name}(transport);\n")
        accessors.append(doc(spec_tag_description(spec, tag), 4, ["@return the resource"]) + f"""    public final {class_name} {accessor}() {{
        return {accessor};
    }}
""")
    content = f"""{HEADER}package {PACKAGE};

{imports_block(imports)}/** The operations of the API by resource. Reach them through {{@link Rask}}. */
public abstract class RaskResources {{
{''.join(fields)}
    RaskResources(Transport transport) {{
{''.join(assigns)}    }}

{chr(10).join(accessors)}}}
"""
    write(out, "RaskResources.java", content)


def clean(out):
    base = os.path.join(out, PACKAGE.replace(".", "/"))
    for folder in ("model", "params", "resources", "."):
        directory = os.path.join(base, folder)
        if not os.path.isdir(directory):
            continue
        for entry in os.listdir(directory):
            path = os.path.join(directory, entry)
            if entry.endswith(".java") and os.path.isfile(path):
                with open(path, encoding="utf-8") as handle:
                    if handle.readline().startswith("// Generated by tools/generate.py"):
                        os.remove(path)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--spec", default="spec/openapi.json")
    parser.add_argument("--out", default="src/main/java")
    args = parser.parse_args()
    with open(args.spec, encoding="utf-8") as handle:
        spec = Spec(json.load(handle))
    clean(args.out)
    for name, schema in spec.schemas.items():
        kind = spec.kind(name)
        if kind == "enum":
            generate_enum(spec, name, schema, args.out)
        elif kind == "union":
            generate_union(spec, name, schema, args.out)
        else:
            generate_object(spec, name, schema, args.out)
    by_tag = {}
    for operation in spec.operations:
        by_tag.setdefault(operation["tag"], []).append(operation)
    for tag, operations in by_tag.items():
        generate_resource(spec, tag, operations, args.out)
    generate_resources_accessors(spec, list(by_tag), args.out)
    print(f"{len(spec.schemas)} schemas, {len(spec.operations)} operations, {len(by_tag)} resources")


if __name__ == "__main__":
    main()
